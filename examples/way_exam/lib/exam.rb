        correct_key: :b,
        explanation: 'PRIMER.md & 0.6: The universal slot model uses contents for body continuation and group for named semantic slots, replacing the legacy children keyword across all partials.'
      )
    ].freeze

    def self.questions
      QUESTIONS
    end

    def self.find(id)
      QUESTIONS.find { |q| q.id.to_s == id.to_s }
    end

    def self.sample_answers
      {
        'q1' => 'a',
        'q2' => 'b',
        'q3' => 'c',
        'q4' => 'b',
        'q5' => 'c',
        'q6' => 'a',
        'q7' => 'b'
      }
    end

    def self.grade(answers = {})
      reviews = QUESTIONS.map do |q|
        raw_ans = answers[q.id] || answers[q.id.to_s] || answers[q.id.to_sym]
        user_key = raw_ans.to_s.strip.downcase.to_sym
        resolved_text = q.options[user_key] || raw_ans.to_s.strip

        correct = (user_key == q.correct_key) || (resolved_text == q.correct_answer)
        display_user_answer = resolved_text.empty? ? '(No answer)' : resolved_text

        Review.new(
          id: q.id,
          number: q.number,
          prompt: q.prompt,
          user_answer: display_user_answer,
          correct_answer: q.correct_answer,
          correct: correct,
          explanation: q.explanation
        )
      end

      score = reviews.count(&:correct)
      total = QUESTIONS.size
      percentage = ((score.to_f / total) * 100).round
      passed = percentage >= 80
      verdict = if percentage == 100
                  'Master of the Way'
                elsif passed
                  'Apprentice of the Way'
                else
                  'Needs Re-reading'
                end

      Result.new(
        score: score,
        total: total,
        percentage: percentage,
        passed: passed,
        verdict: verdict,
        reviews: reviews
      )
    end
  end
end
